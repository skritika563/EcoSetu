/**
 * Pickup mock data — addresses, collectors, time slots, and the pickup
 * records themselves.
 *
 * Shaped to match POST /api/pickups (API_SPEC.md §3.3) and the Pickup /
 * ScrapRates collections (DATABASE_SCHEMA.md §3.2–3.3), so swapping to the
 * real API later is a service-layer change, not a UI rewrite.
 *
 * A pickup record is ONE shared shape used from both sides of the same
 * transaction: `customer` is who booked it (shown to the collector),
 * `collector` is who it's assigned to (shown to the household/organization).
 * Whichever role is signed in only ever renders the side that applies to
 * them — see services/pickupService.js.
 *
 * Three IDs are intentionally pinned so Home's existing hero cards link to a
 * real, consistent detail page without Home's own mock data being touched:
 *   PKP-2417 — household's upcoming pickup (dashboardData.HOUSEHOLD_DASHBOARD)
 *   PKP-2455 — organization's upcoming pickup (…ORGANIZATION_DASHBOARD)
 *   JOB-8821 — collector's next job (…COLLECTOR_DASHBOARD)
 */

