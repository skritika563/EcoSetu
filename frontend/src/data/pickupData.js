/**
 * Mock slot availability for a given date — deterministic per date (not
 * random per render), so a date's availability doesn't shuffle if the user
 * navigates back and forth. Not connected to a real scheduling backend.
 */
export const getSlotAvailability = (dateISO) => {
  const seed = new Date(dateISO).getDate();
  return TIME_SLOTS.map((slot, i) => ({
    ...slot,
    available: (seed + i) % 5 !== 0,
  }));
};

/** Next 7 selectable pickup dates (today excluded — same-day needs Instant). */
export const getBookableDates = () => Array.from({ length: 7 }, (_, i) => daysFromNow(i + 1));

